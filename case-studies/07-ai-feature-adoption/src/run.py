"""
Run the opt-in AI feature adoption case study end-to-end.

Usage (from the repository root):
    python case-studies/07-ai-feature-adoption/src/run.py

Writes:
    case-studies/07-ai-feature-adoption/results.md
    case-studies/07-ai-feature-adoption/docs/hero.png
"""

from __future__ import annotations

import sys
from pathlib import Path

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt  # noqa: E402
import pandas as pd  # noqa: E402

sys.path.insert(0, str(Path(__file__).parent))

from adoption_estimators import ESTIMATOR_LABELS, ESTIMATORS  # noqa: E402
from adoption_mc import run_scenario, summarize  # noqa: E402
from adoption_simulate import SCENARIOS, population_truth  # noqa: E402

SEED = 0
N_REPS = 1000
N_USERS = 4000

CASE = Path(__file__).resolve().parents[1]
RESULTS = CASE / "results.md"
HERO = CASE / "docs" / "hero.png"
COLORS = {"naive": "#7f7f7f", "aipw_x": "#1f77b4", "aipw_x_pre": "#2ca02c", "did": "#d62728"}


def _table(header: list[str], rows: list[list[str]]) -> str:
    lines = ["| " + " | ".join(header) + " |", "|" + "---|" * len(header)]
    lines += ["| " + " | ".join(r) + " |" for r in rows]
    return "\n".join(lines)


def _pct(x: float) -> str:
    return f"{100 * x:.1f}%"


def write_results(summary: pd.DataFrame) -> None:
    parts = [
        "# Results: opt-in AI feature adoption",
        "",
        "Generated by `python case-studies/07-ai-feature-adoption/src/run.py`. "
        "Do not edit by hand.",
        "",
        f"Settings: seed = {SEED}, {N_REPS} replications per scenario, "
        f"{N_USERS:,} users per replication, 95% intervals, placebo flags at |z| > 1.96.",
        f"One Monte Carlo standard error at {N_REPS} replications: "
        f"{100 * (0.95 * 0.05 / N_REPS) ** 0.5:.1f} percentage points on a 95% or 5% rate, "
        f"{100 * (0.5 * 0.5 / N_REPS) ** 0.5:.1f} points on a 50% rate.",
        "",
        "## Ground truth by construction",
        "",
    ]
    truth_rows = []
    for name, sc in SCENARIOS.items():
        t = population_truth(sc)
        truth_rows.append(
            [f"`{name}`", sc.label, f"{t['att']:.3f}", f"{t['ate']:.3f}", _pct(t["adopt_rate"])]
        )
    parts += [
        _table(["Scenario", "Selection channel", "True ATT", "True ATE", "Adoption rate"],
               truth_rows),
        "",
        "## Estimators against the true ATT",
        "",
        "Bias = mean estimate minus true ATT. Placebo flag = share of replications where the "
        "same estimator, run one period earlier with a fake launch, rejects zero. "
        "E-values use `sensitivity.e_value` with the non-adopter post-period SD.",
        "",
    ]
    header = ["Estimator", "Mean est.", "True ATT", "Bias", "Emp. SD", "Mean SE", "Coverage",
              "Rejects 0", "Placebo flags", "Median E-value (point / CI)"]
    for name, sc in SCENARIOS.items():
        rows = []
        for _, r in summary[summary["scenario"] == name].iterrows():
            rows.append([
                ESTIMATOR_LABELS[r["estimator"]],
                f"{r['mean_est']:+.3f}",
                f"{r['true_att']:+.3f}",
                f"{r['bias']:+.3f}",
                f"{r['emp_sd']:.3f}",
                f"{r['mean_se']:.3f}",
                _pct(r["coverage"]),
                _pct(r["reject_zero"]),
                _pct(r["placebo_flag"]),
                f"{r['median_e_value']:.2f} / {r['median_e_value_ci']:.2f}",
            ])
        parts += [f"### `{name}`: {sc.label}", "", _table(header, rows), ""]

    parts += [
        "## Gated decision: act only if the placebo passes and the CI excludes zero",
        "",
        "Each cell shows how often the gate says act, then how often it says act while the CI "
        "misses the true ATT (a confident wrong answer).",
        "",
    ]
    gate_rows = []
    for name in SCENARIOS:
        s = summary[summary["scenario"] == name].set_index("estimator")
        gate_rows.append(
            [f"`{name}`"]
            + [f"{_pct(s.loc[e, 'acts'])} / {_pct(s.loc[e, 'acts_wrong'])}" for e in ESTIMATORS]
        )
    parts += [_table(["Scenario"] + [ESTIMATOR_LABELS[e] for e in ESTIMATORS], gate_rows), ""]
    RESULTS.write_text("\n".join(parts), encoding="utf-8", newline="\n")


def make_chart(draws: pd.DataFrame, summary: pd.DataFrame) -> None:
    names = list(SCENARIOS)
    fig, (ax_l, ax_r) = plt.subplots(1, 2, figsize=(12, 6.2), sharey=True,
                                     gridspec_kw={"width_ratios": [1.6, 1]})
    step = 1.0 / (len(ESTIMATORS) + 1)
    for i, name in enumerate(names):
        for j, est in enumerate(ESTIMATORS):
            y = i + (j - (len(ESTIMATORS) - 1) / 2) * step
            g = draws[(draws["scenario"] == name) & (draws["estimator"] == est)]
            err = g["est"] - g["true_att"]
            lo, hi = err.quantile([0.025, 0.975])
            label = ESTIMATOR_LABELS[est] if i == 0 else None
            ax_l.errorbar(err.mean(), y, xerr=[[err.mean() - lo], [hi - err.mean()]], fmt="o",
                          color=COLORS[est], capsize=3, ms=5, label=label)
            flag = summary[(summary["scenario"] == name) & (summary["estimator"] == est)]
            ax_r.barh(y, flag["placebo_flag"].iloc[0], height=step * 0.9, color=COLORS[est])
    ax_l.axvline(0, color="black", lw=1)
    ax_l.set_xlabel(
        "Estimate minus true ATT (sessions/week)\ndot = mean, bar = middle 95% of replications"
    )
    ax_l.set_title("Bias against the known ATT")
    ax_l.set_yticks(range(len(names)))
    ax_l.set_yticklabels([SCENARIOS[n].label for n in names], fontsize=9)
    ax_l.invert_yaxis()
    ax_l.grid(True, axis="x", alpha=0.3)
    ax_r.axvline(0.05, color="black", lw=1, ls="--")
    ax_r.set_xlim(0, 1)
    ax_r.set_xlabel("Share of replications where the placebo flags\n(dashed line = 5% nominal)")
    ax_r.set_title("Does the fake-launch placebo catch it?")
    ax_r.grid(True, axis="x", alpha=0.3)
    fig.suptitle(
        "Case 07: adopters of an opt-in AI feature, "
        f"{N_REPS} simulated replications x {N_USERS:,} users",
        fontsize=12,
    )
    fig.legend(loc="lower center", ncol=len(ESTIMATORS), fontsize=9, frameon=False)
    fig.tight_layout(rect=(0, 0.05, 1, 1))
    HERO.parent.mkdir(parents=True, exist_ok=True)
    fig.savefig(HERO, dpi=130, metadata={"Software": None})
    plt.close(fig)


def main() -> None:
    draws = pd.concat([run_scenario(n, N_REPS, N_USERS, seed=SEED) for n in SCENARIOS],
                      ignore_index=True)
    summary = summarize(draws)
    write_results(summary)
    make_chart(draws, summary)
    cols = ["scenario", "estimator", "true_att", "bias", "coverage", "placebo_flag", "acts_wrong"]
    print(summary[cols].round(3).to_string(index=False))
    print(f"\nwrote {RESULTS.relative_to(CASE.parents[1])}")
    print(f"wrote {HERO.relative_to(CASE.parents[1])}")


if __name__ == "__main__":
    main()
