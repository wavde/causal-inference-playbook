"""
Run case 08: staggered rollout vs fixed holdout for an opt-in AI feature.

Usage (from the repository root):
    python case-studies/08-rollout-vs-holdout/src/run.py
    python case-studies/08-rollout-vs-holdout/src/run.py --smoke   # CI: tiny, temp output

Writes:
    case-studies/08-rollout-vs-holdout/results.md
    case-studies/08-rollout-vs-holdout/docs/hero.png
"""

from __future__ import annotations

import argparse
import sys
import tempfile
from pathlib import Path

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt  # noqa: E402
import numpy as np  # noqa: E402

sys.path.insert(0, str(Path(__file__).parent))

from rollout import (  # noqa: E402
    Population,
    RolloutDesign,
    analyze,
    simulate_panel,
    true_itt,
)

SEED = 20261127
N_REPS = 1000
CASE = Path(__file__).resolve().parents[1]
POP = Population()
_D = np.arange(POP.post)
SHAPES = {
    "null": ("No effect", np.zeros(POP.post)),
    "flat": ("Flat: 0.30 every week", np.full(POP.post, 0.30)),
    "learning": ("Learning: grows to 0.30", 0.30 * (1 - 0.6 ** (_D + 1))),
    "novelty": ("Novelty: 0.40, fades 40% a week", 0.40 * 0.6**_D),
}
DESIGNS = (
    RolloutDesign("Fixed holdout: 10% never get access", ((0.90, 0), (0.10, None))),
    RolloutDesign("Staggered: 40% get access 2 weeks late", ((0.60, 0), (0.40, 2))),
    RolloutDesign(
        "Hybrid: 20% two weeks late + 5% holdout", ((0.75, 0), (0.20, 2), (0.05, None))
    ),
)
ESTIMANDS = {"short": "Short-run ITT (weeks 0-1)", "long": "Long-run ITT (weeks 6-7)",
             "shape": "Long minus short"}


def run(rng: np.random.Generator, n_reps: int) -> dict:
    out = {}
    for s_key, (_, tau) in SHAPES.items():
        truth = true_itt(POP, tau)
        for design in DESIGNS:
            draws: dict[str, list] = {}
            for _ in range(n_reps):
                res = analyze(simulate_panel(POP, design, tau, rng), design, POP)
                for k, e in res.items():
                    draws.setdefault(k, []).append(
                        (e.estimate, e.se, e.covers(truth[k]), e.significant(),
                         e.significant() and e.estimate > 0)
                    )
            out[(s_key, design.name)] = (truth, {k: np.array(v) for k, v in draws.items()})
    return out


def results_md(res: dict, n_reps: int, path: Path) -> None:
    truth0 = true_itt(POP, SHAPES["flat"][1])
    mc = 100 * (0.05 * 0.95 / n_reps) ** 0.5
    lines = [
        "# Results: staggered rollout vs fixed holdout for an opt-in AI feature",
        "",
        "Generated by `python case-studies/08-rollout-vs-holdout/src/run.py`. Do not edit by "
        "hand.",
        "",
        f"Seed {SEED}. {n_reps} replications per cell. {POP.n:,} users, {POP.pre} pre-launch and "
        f"{POP.post} post-launch weeks, user effect SD {POP.user_sd}, weekly noise SD 1. "
        f"Users with access opt in with probability rising in their user effect; the adoption "
        f"rate is {truth0['adoption']:.1%}. Adopters gain tau(d) in week d after access. All "
        "three designs withhold access from "
        + ", ".join(f"{d.withheld_share(POP.post):.0%}" for d in DESIGNS)
        + " of post-launch user-weeks. Contrasts are CUPED-adjusted with each user's pre-launch "
        f"mean. One Monte Carlo SE on a 5% rate is {mc:.1f} points.",
        "",
        "## Ground truth by construction",
        "",
        "| Effect shape | True short-run ITT | True long-run ITT | Long minus short |",
        "|---|---:|---:|---:|",
    ]
    for label, tau in SHAPES.values():
        t = true_itt(POP, tau)
        lines.append(f"| {label} | {t['short']:+.4f} | {t['long']:+.4f} | {t['shape']:+.4f} |")
    lines += [
        "",
        "## Every estimate against its truth",
        "",
        "A dash means the design cannot identify that estimand: without a holdout, no one is "
        "untreated in weeks 6-7.",
        "",
        "| Effect shape | Design | Estimand | Truth | Mean estimate | Emp. SD | Mean SE "
        "| Coverage | Rejects 0 |",
        "|---|---|---|---:|---:|---:|---:|---:|---:|",
    ]
    for (s_key, d_name), (truth, draws) in res.items():
        for k, label in ESTIMANDS.items():
            if k not in draws:
                lines.append(f"| {SHAPES[s_key][0]} | {d_name} | {label} | {truth[k]:+.4f} "
                             "| — | — | — | — | — |")
                continue
            a = draws[k]
            lines.append(
                f"| {SHAPES[s_key][0]} | {d_name} | {label} | {truth[k]:+.4f} "
                f"| {a[:, 0].mean():+.4f} | {a[:, 0].std(ddof=1):.4f} | {a[:, 1].mean():.4f} "
                f"| {a[:, 2].mean():.1%} | {a[:, 3].mean():.1%} |"
            )
    lines += [
        "",
        "## The launch decision",
        "",
        "Each design ships when the estimate it can produce for the longest horizon is "
        "significantly positive. That is the long-run ITT when there is a holdout and the "
        "short-run ITT otherwise. The right call is to ship when the true long-run ITT is "
        "meaningfully positive, and not to ship under no effect or a novelty effect that "
        "fades to near zero (true long-run ITT "
        f"{true_itt(POP, SHAPES['novelty'][1])['long']:+.4f}). The last column is how often "
        "the shape test flags that the effect changed between the short and long windows.",
        "",
        "| Effect shape | Design | Ships | Flags a change in effect |",
        "|---|---|---:|---:|",
    ]
    for (s_key, d_name), (_, draws) in res.items():
        key = "long" if "long" in draws else "short"
        ships = draws[key][:, 4].mean()
        shape = f"{draws['shape'][:, 3].mean():.1%}" if "shape" in draws else "—"
        lines.append(f"| {SHAPES[s_key][0]} | {d_name} | {ships:.1%} | {shape} |")
    lines.append("")
    path.write_text("\n".join(lines), encoding="utf-8", newline="\n")


def chart(res: dict, path: Path) -> None:
    fig, axes = plt.subplots(1, 2, figsize=(12, 4.6))
    colors = ("#1f77b4", "#d62728", "#2ca02c")
    shapes = list(SHAPES)
    width = 0.26
    x = np.arange(len(shapes))
    for i, (design, color) in enumerate(zip(DESIGNS, colors, strict=True)):
        ships = []
        for s in shapes:
            draws = res[(s, design.name)][1]
            ships.append(100 * draws["long" if "long" in draws else "short"][:, 4].mean())
        axes[0].bar(x + (i - 1) * width, ships, width, color=color, label=design.name)
    axes[0].set_xticks(x, [SHAPES[s][0].split(":")[0] for s in shapes])
    axes[0].set_ylabel("Ships (%)")
    axes[0].set_ylim(0, 150)
    axes[0].set_yticks(range(0, 101, 20))
    axes[0].set_title("How often each design ships\n(right call: ship Flat and Learning only)")
    axes[0].legend(fontsize=8, loc="upper center", ncol=1)
    axes[0].grid(True, axis="y", alpha=0.3)

    ax = axes[1]
    for i, (design, color) in enumerate(zip(DESIGNS, colors, strict=True)):
        for j, k in enumerate(("short", "long")):
            draws = res[("novelty", design.name)][1]
            if k not in draws:
                continue
            est = draws[k][:, 0]
            y = j + (i - 1) * 0.22
            lo, hi = np.quantile(est, [0.025, 0.975])
            ax.errorbar(est.mean(), y, xerr=[[est.mean() - lo], [hi - est.mean()]], fmt="o",
                        color=color, capsize=3)
    truth = true_itt(POP, SHAPES["novelty"][1])
    for j, k in enumerate(("short", "long")):
        ax.plot([truth[k]] * 2, [j - 0.4, j + 0.4], color="black", ls="--", lw=1)
    ax.set_yticks([0, 1], ["Short-run\n(weeks 0-1)", "Long-run\n(weeks 6-7)"])
    ax.axvline(0, color="grey", lw=0.8)
    ax.set_xlabel("ITT estimate (dashed = truth; bar = middle 95% of replications)")
    ax.set_title("Novelty effect: what each design measures\n(colors as on the left)")
    ax.grid(True, axis="x", alpha=0.3)
    fig.suptitle("Same 10% of user-weeks withheld, three designs", fontsize=12, y=1.0)
    fig.tight_layout()
    path.parent.mkdir(parents=True, exist_ok=True)
    fig.savefig(path, dpi=130, bbox_inches="tight", metadata={"Software": None})
    plt.close(fig)


def main() -> None:
    parser = argparse.ArgumentParser(description="Case 08: staggered rollout vs holdout")
    parser.add_argument("--smoke", action="store_true", help="tiny run, output to a temp dir")
    args = parser.parse_args()
    n_reps = 3 if args.smoke else N_REPS
    out = Path(tempfile.mkdtemp()) if args.smoke else CASE
    res = run(np.random.default_rng(SEED), n_reps)
    results_md(res, n_reps, out / "results.md")
    chart(res, out / "docs" / "hero.png")
    print(f"wrote {out / 'results.md'}")
    print(f"wrote {out / 'docs' / 'hero.png'}")


if __name__ == "__main__":
    main()
